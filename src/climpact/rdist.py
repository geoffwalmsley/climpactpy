def _exp(x: float) -> float:
    """C exp: overflow gives +Inf rather than an exception."""
    try:
        return math.exp(x)
    except OverflowError:
        return math.inf


def _r_d_exp(x: float, log_p: bool) -> float:
    return x if log_p else _exp(x)


def _r_log1_exp(x: float) -> float:
    """R_Log1_Exp(x): log(1 - exp(x))."""
    return math.log(-math.expm1(x)) if x > -_M_LN2 else math.log1p(-_exp(x))


def _chebyshev_eval(x: float, a: tuple[float, ...], n: int) -> float:
    if x < -1.1 or x > 1.1:
        return math.nan
    twox = x * 2
    b2 = b1 = b0 = 0.0
    for i in range(1, n + 1):
        b2 = b1
        b1 = b0
        b0 = twox * b1 - b2 + a[n - i]
    return (b0 - b2) * 0.5


