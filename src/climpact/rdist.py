def _lgammacor(x: float) -> float:
    if x < 10:
        return math.nan
    if x < 94906265.62425156:
        tmp = 10 / x
        return _chebyshev_eval(tmp * tmp * 2 - 1, _ALGMCS, 5) / x
    return 1 / (x * 12)


def lgammafn(x: float) -> float:
    """R lgammafn (lgamma.c) for x > 0."""
    if math.isnan(x):
        return x
    if x <= 0:
        raise ValueError("lgammafn is only ported for x > 0")
    if x < 1e-306:
        return -math.log(x)
    if x <= 10:
        return math.log(abs(_gammafn_small(x)))
    if x > 2.5327372760800758e305:
        return math.inf
    if x > 1e17:
        return x * (math.log(x) - 1.0)
    if x > 4934720.0:
        return _M_LN_SQRT_2PI + (x - 0.5) * math.log(x) - x
    return _M_LN_SQRT_2PI + (x - 0.5) * math.log(x) - x + _lgammacor(x)


def _logcf(x: float, i: float, d: float, eps: float) -> float:
    c1 = 2 * d
    c2 = i + d
    c4 = c2 + d
    a1 = c2
    b1 = i * (c2 - i * x)
    b2 = d * d * x
    a2 = c4 * c2 - b2
    b2 = c4 * b1 - i * b2
    while abs(a2 * b1 - a1 * b2) > abs(eps * b1 * b2):
        c3 = c2 * c2 * x
        c2 += d
        c4 += d
        a1 = c4 * a2 - c3 * a1
        b1 = c4 * b2 - c3 * b1
        c3 = c1 * c1 * x
        c1 += d
        c4 += d
        a2 = c4 * a1 - c3 * a2
        b2 = c4 * b1 - c3 * b2
        if abs(b2) > _SCALEFACTOR:
            a1 /= _SCALEFACTOR
            b1 /= _SCALEFACTOR
            a2 /= _SCALEFACTOR
            b2 /= _SCALEFACTOR
        elif abs(b2) < 1 / _SCALEFACTOR:
            a1 *= _SCALEFACTOR
            b1 *= _SCALEFACTOR
            a2 *= _SCALEFACTOR
            b2 *= _SCALEFACTOR
    return a2 / b2


def log1pmx(x: float) -> float:
    """R log1pmx: log(1 + x) - x."""
    if x > 1 or x < -0.79149064:
        return math.log1p(x) - x
    r = x / (2 + x)
    y = r * r
    if abs(x) < 1e-2:
        two = 2.0
        return r * ((((two / 9 * y + two / 7) * y + two / 5) * y + two / 3) * y - x)
    return r * (2 * y * _logcf(y, 3, 2, 1e-14) - x)


