def lgamma1p(a: float) -> float:
    """R lgamma1p: log(gamma(1 + a)), accurate for small a."""
    if abs(a) >= 0.5:
        return lgammafn(a + 1)
    eulers_const = 0.5772156649015328606065120900824024
    n = 40
    c = 0.2273736845824652515226821577978691e-12
    lgam = c * _logcf(-a / 2, n + 2, 1, 1e-14)
    for i in range(n - 1, -1, -1):
        lgam = _LGAMMA1P_COEFFS[i] - a * lgam
    return (a * lgam - eulers_const) * a - log1pmx(a)


