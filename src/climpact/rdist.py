def libm_lgamma(x: float) -> float:
    """C ``lgamma`` as in glibc (``e_lgamma_r.c``, from fdlibm), for ``x > 0``.

    R's ``stirlerr`` calls the C library's ``lgamma``. Python's ``math.lgamma`` is
    CPython's own implementation and differs in the last bits, so glibc's is ported.
    """
    if not x > 0 or not math.isfinite(x):
        raise ValueError("only finite x > 0 is supported")
    a, t, u, v, s, r_, w = _LG_A, _LG_T, _LG_U, _LG_V, _LG_S, _LG_R, _LG_W
    ix = _high_word(x)
    if ix < 0x3B900000:
        return -math.log(x)
    if x == 1.0 or x == 2.0:
        return 0.0
    if ix < 0x40000000:
        if ix <= 0x3FECCCCC:
            r = -math.log(x)
            if ix >= 0x3FE76944:
                y, i = 1.0 - x, 0
            elif ix >= 0x3FCDA661:
                y, i = x - (_LG_TC - 1.0), 1
            else:
                y, i = x, 2
        else:
            r = 0.0
            if ix >= 0x3FFBB4C3:
                y, i = 2.0 - x, 0
            elif ix >= 0x3FF3B4C4:
                y, i = x - _LG_TC, 1
            else:
                y, i = x - 1.0, 2
        if i == 0:
            z = y * y
            p1 = a[0] + z * (a[2] + z * (a[4] + z * (a[6] + z * (a[8] + z * a[10]))))
            p2 = z * (a[1] + z * (a[3] + z * (a[5] + z * (a[7] + z * (a[9] + z * a[11])))))
            p = y * p1 + p2
            r += p - 0.5 * y
        elif i == 1:
            z = y * y
            ww = z * y
            p1 = t[0] + ww * (t[3] + ww * (t[6] + ww * (t[9] + ww * t[12])))
            p2 = t[1] + ww * (t[4] + ww * (t[7] + ww * (t[10] + ww * t[13])))
            p3 = t[2] + ww * (t[5] + ww * (t[8] + ww * (t[11] + ww * t[14])))
            p = z * p1 - (_LG_TT - ww * (p2 + y * p3))
            r += _LG_TF + p
        else:
            p1 = y * (u[0] + y * (u[1] + y * (u[2] + y * (u[3] + y * (u[4] + y * u[5])))))
            p2 = 1.0 + y * (v[1] + y * (v[2] + y * (v[3] + y * (v[4] + y * v[5]))))
            r += -0.5 * y + p1 / p2
        return r
    if ix < 0x40200000:  # x < 8
        i = int(x)
        y = x - float(i)
        p = y * (s[0] + y * (s[1] + y * (s[2] + y * (s[3] + y * (s[4] + y * (s[5] + y * s[6]))))))
        q = 1.0 + y * (r_[1] + y * (r_[2] + y * (r_[3] + y * (r_[4] + y * (r_[5] + y * r_[6])))))
        r = 0.5 * y + p / q
        z = 1.0
        for k in range(i, 2, -1):  # switch fall-through: case 7 ... case 3
            z *= y + (k - 1.0)
        if i >= 3:
            r += math.log(z)
        return r
    if ix < 0x43900000:
        tl = math.log(x)
        z = 1.0 / x
        y = z * z
        ww = w[0] + z * (w[1] + y * (w[2] + y * (w[3] + y * (w[4] + y * (w[5] + y * w[6])))))
        return (x - 0.5) * (tl - 1.0) + ww
    return x * (math.log(x) - 1.0)


