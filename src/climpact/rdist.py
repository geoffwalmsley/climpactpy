def ebd0(x: float, m: float) -> tuple[float, float]:
    """R ebd0: x log(x / M) + M - x in two parts (yh, yl) (bd0.c)."""
    sb = 10
    s = float(1 << sb)
    n = 128
    yh = yl = 0.0
    if x == m:
        return yh, yl
    if x == 0:
        return m, yl
    if m == 0:
        return math.inf, yl
    if m / x == math.inf:
        return m, yl
    r, e = math.frexp(m / x)
    if _M_LN2 * float(-e) > 1.0 + _DBL_MAX / x:
        return math.inf, yl
    i = int(math.floor((r - 0.5) * (2 * n) + 0.5))
    f = math.floor(s / (0.5 + i / (2.0 * n)) + 0.5)
    try:
        fg = math.ldexp(f, -(e + sb))
    except OverflowError:
        fg = math.inf
    if fg == math.inf:
        return fg, yl

    def add1(d: float) -> None:
        nonlocal yh, yl
        d1 = math.floor(d + 0.5)
        d2 = d - d1
        yh += d1
        yl += d2

    add1(-x * log1pmx((m * fg - x) / x))
    if fg == 1:
        return yh, yl
    for j in range(4):
        add1(x * _BD0_SCALE[i][j])
        add1(-x * _BD0_SCALE[0][j] * e)
        if not math.isfinite(yh):
            return math.inf, 0.0
    add1(m)
    add1(-m * fg)
    return yh, yl


def dpois_raw(x: float, lam: float, give_log: bool) -> float:
    """R dpois_raw (dpois.c)."""
    zero, one = (-math.inf, 0.0) if give_log else (0.0, 1.0)
    if lam == 0:
        return one if x == 0 else zero
    if not math.isfinite(lam) or x < 0:
        return zero
    if x <= lam * _DBL_MIN:
        return _r_d_exp(-lam, give_log)
    if lam < x * _DBL_MIN:
        if not math.isfinite(x):
            return zero
        return _r_d_exp(-lam + x * math.log(lam) - lgammafn(x + 1), give_log)
    yh, yl = ebd0(x, lam)
    yl += stirlerr(x)
    large = x >= _X_LRG
    r = _M_SQRT_2PI * math.sqrt(x) if large else _M_2PI * x
    if give_log:
        return -yl - yh - (math.log(r) if large else 0.5 * math.log(r))
    return _exp(-yl) * _exp(-yh) / (r if large else math.sqrt(r))


def _dpois_wrap(x_plus_1: float, lam: float, give_log: bool) -> float:
    if not math.isfinite(lam):
        return -math.inf if give_log else 0.0
    if x_plus_1 > 1:
        return dpois_raw(x_plus_1 - 1, lam, give_log)
    if lam > abs(x_plus_1 - 1) * _M_CUTOFF:
        return _r_d_exp(-lam - lgammafn(x_plus_1), give_log)
    d = dpois_raw(x_plus_1, lam, give_log)
    return d + math.log(x_plus_1 / lam) if give_log else d * (x_plus_1 / lam)


def _pgamma_smallx(x: float, alph: float, lower_tail: bool, log_p: bool) -> float:
    total = 0.0
    c = alph
    n = 0.0
    while True:
        n += 1
        c *= -x / n
        term = c / (alph + n)
        total += term
        if not abs(term) > _DBL_EPSILON * abs(total):
            break
    if lower_tail:
        f1 = math.log1p(total) if log_p else 1 + total
        if alph > 1:
            f2 = dpois_raw(alph, x, log_p)
            f2 = f2 + x if log_p else f2 * _exp(x)
        elif log_p:
            f2 = alph * math.log(x) - lgamma1p(alph)
        else:
            f2 = math.pow(x, alph) / _exp(lgamma1p(alph))
        return f1 + f2 if log_p else f1 * f2
    lf2 = alph * math.log(x) - lgamma1p(alph)
    if log_p:
        return _r_log1_exp(math.log1p(total) + lf2)
    f1m1 = total
    f2m1 = math.expm1(lf2)
    return -(f1m1 + f2m1 + f1m1 * f2m1)


def _pd_upper_series(x: float, y: float, log_p: bool) -> float:
    term = x / y
    total = term
    while True:
        y += 1
        term *= x / y
        total += term
        if not term > total * _DBL_EPSILON:
            break
    return math.log(total) if log_p else total


def _pd_lower_cf(y: float, d: float) -> float:
    f = 0.0
    if y == 0:
        return 0.0
    f0 = y / d
    if abs(y - 1) < abs(d) * _DBL_EPSILON:
        return f0
    if f0 > 1.0:
        f0 = 1.0
    c2 = y
    c4 = d
    a1, b1 = 0.0, 1.0
    a2, b2 = y, d
    while b2 > _SCALEFACTOR:
        a1 /= _SCALEFACTOR
        b1 /= _SCALEFACTOR
        a2 /= _SCALEFACTOR
        b2 /= _SCALEFACTOR
    i = 0.0
    of = -1.0
    while i < 200000:
        i += 1
        c2 -= 1
        c3 = i * c2
        c4 += 2
        a1 = c4 * a2 + c3 * a1
        b1 = c4 * b2 + c3 * b1
        i += 1
        c2 -= 1
        c3 = i * c2
        c4 += 2
        a2 = c4 * a1 + c3 * a2
        b2 = c4 * b1 + c3 * b2
        if b2 > _SCALEFACTOR:
            a1 /= _SCALEFACTOR
            b1 /= _SCALEFACTOR
            a2 /= _SCALEFACTOR
            b2 /= _SCALEFACTOR
        if b2 != 0:
            f = a2 / b2
            if abs(f - of) <= _DBL_EPSILON * max(f0, abs(f)):
                return f
            of = f
    return f


def _pd_lower_series(lam: float, y: float) -> float:
    term = 1.0
    total = 0.0
    while y >= 1 and term > total * _DBL_EPSILON:
        term *= y / lam
        total += term
        y -= 1
    if y != math.floor(y):
        f = _pd_lower_cf(y, lam + 1 - y)
        total += term * f
    return total


def _dpnorm(x: float, lower_tail: bool, lp: float) -> float:
    if x < 0:
        x = -x
        lower_tail = not lower_tail
    if x > 10 and not lower_tail:
        term = 1 / x
        total = term
        x2 = x * x
        i = 1.0
        while True:
            term *= -i / x2
            total += term
            i += 2
            if not abs(term) > _DBL_EPSILON * total:
                break
        return 1 / total
    return dnorm(x) / _exp(lp)


_COEFS_A = (
    -1e99,
    2 / 3.0,
    -4 / 135.0,
    8 / 2835.0,
    16 / 8505.0,
    -8992 / 12629925.0,
    -334144 / 492567075.0,
    698752 / 1477701225.0,
)
_COEFS_B = (
    -1e99,
    1 / 12.0,
    1 / 288.0,
    -139 / 51840.0,
    -571 / 2488320.0,
    163879 / 209018880.0,
    5246819 / 75246796800.0,
    -534703531 / 902961561600.0,
)


def _ppois_asymp(x: float, lam: float, lower_tail: bool, log_p: bool) -> float:
    dfm = lam - x
    pt_ = -log1pmx(dfm / x)
    s2pt = math.sqrt(2 * x * pt_)
    if dfm < 0:
        s2pt = -s2pt
    res12 = 0.0
    res1_ig = res1_term = math.sqrt(x)
    res2_ig = res2_term = s2pt
    for i in range(1, 8):
        res12 += res1_ig * _COEFS_A[i]
        res12 += res2_ig * _COEFS_B[i]
        res1_term *= pt_ / i
        res2_term *= 2 * pt_ / (2 * i + 1)
        res1_ig = res1_ig / x + res1_term
        res2_ig = res2_ig / x + res2_term
    elfb = x
    elfb_term = 1.0
    for i in range(1, 8):
        elfb += elfb_term * _COEFS_B[i]
        elfb_term /= x
    if not lower_tail:
        elfb = -elfb
    f = res12 / elfb
    np_ = pnorm(s2pt, not lower_tail, log_p)
    if log_p:
        n_d_over_p = _dpnorm(s2pt, not lower_tail, np_)
        return np_ + math.log1p(f * n_d_over_p)
    nd = dnorm(s2pt)
    return np_ + f * nd


def _pgamma_raw(x: float, alph: float, lower_tail: bool, log_p: bool) -> float:
    if x <= 0:
        return (-math.inf if log_p else 0.0) if lower_tail else (0.0 if log_p else 1.0)
    if x == math.inf:
        return (0.0 if log_p else 1.0) if lower_tail else (-math.inf if log_p else 0.0)
    if x < 1:
        res = _pgamma_smallx(x, alph, lower_tail, log_p)
    elif x <= alph - 1 and x < 0.8 * (alph + 50):
        total = _pd_upper_series(x, alph, log_p)
        d = _dpois_wrap(alph, x, log_p)
        if not lower_tail:
            res = _r_log1_exp(d + total) if log_p else 1 - d * total
        else:
            res = total + d if log_p else total * d
    elif alph - 1 < x and alph < 0.8 * (x + 50):
        d = _dpois_wrap(alph, x, log_p)
        if alph < 1:
            if x * _DBL_EPSILON > 1 - alph:
                total = 0.0 if log_p else 1.0
            else:
                f = _pd_lower_cf(alph, x - (alph - 1)) * x / alph
                total = math.log(f) if log_p else f
        else:
            total = _pd_lower_series(x, alph - 1)
            total = math.log1p(total) if log_p else 1 + total
        if not lower_tail:
            res = total + d if log_p else total * d
        else:
            res = _r_log1_exp(d + total) if log_p else 1 - d * total
    else:
        res = _ppois_asymp(alph - 1, x, not lower_tail, log_p)
    if not log_p and res < _DBL_MIN / _DBL_EPSILON:
        return _exp(_pgamma_raw(x, alph, lower_tail, True))
    return res


def pgamma(q: float, shape: float, scale: float = 1.0) -> float:
    """R pgamma(q, shape, scale = scale) (lower tail, pgamma.c).

    The argument is divided by scale first, as in R.
    """
    if math.isnan(q) or math.isnan(shape) or math.isnan(scale):
        return math.nan
    if shape < 0 or scale <= 0:
        return math.nan
    x = q / scale
    if math.isnan(x):
        return x
    if shape == 0:
        return 0.0 if x <= 0 else 1.0
    return _pgamma_raw(x, shape, True, False)
