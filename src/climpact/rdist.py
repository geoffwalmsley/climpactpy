def _gammafn_small(x: float) -> float:
    """R gammafn for 0 < x <= 10 (the only range used here)."""
    n = int(x)
    y = x - n
    n -= 1
    value = _chebyshev_eval(y * 2 - 1, _GAMCS, 22) + 0.9375
    if n == 0:
        return value
    if n < 0:
        for i in range(-n):
            value /= x + i
        return value
    for i in range(1, n + 1):
        value *= y + i
    return value


