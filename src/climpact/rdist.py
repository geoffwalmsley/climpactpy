def _pnorm_both(x: float, lower: bool, log_p: bool) -> float:
    """pnorm_both for one tail (lower or upper), on the log scale if log_p."""
    upper = not lower
    y = abs(x)
    if y <= 0.67448975:
        if y > _DBL_EPSILON * 0.5:
            xsq = x * x
            xnum = _A[4] * xsq
            xden = xsq
            for i in range(3):
                xnum = (xnum + _A[i]) * xsq
                xden = (xden + _B[i]) * xsq
        else:
            xnum = xden = 0.0
        temp = x * (xnum + _A[3]) / (xden + _B[3])
        result = 0.5 + temp if lower else 0.5 - temp
        return math.log(result) if log_p else result
    if y <= _M_SQRT_32:
        xnum = _C[8] * y
        xden = y
        for i in range(7):
            xnum = (xnum + _C[i]) * y
            xden = (xden + _D[i]) * y
        temp = (xnum + _C[7]) / (xden + _D[7])
        return _do_del(x, y, temp, lower, log_p)
    if (
        (log_p and y < 1e170)
        or (lower and -38.4674 < x < 8.2924)
        or (upper and -8.2924 < x < 38.4674)
    ):
        xsq = 1.0 / (x * x)
        xnum = _P[5] * xsq
        xden = xsq
        for i in range(4):
            xnum = (xnum + _P[i]) * xsq
            xden = (xden + _Q[i]) * xsq
        temp = xsq * (xnum + _P[4]) / (xden + _Q[4])
        temp = (_M_1_SQRT_2PI - temp) / y
        return _do_del(x, x, temp, lower, log_p)
    one, zero = (0.0, -math.inf) if log_p else (1.0, 0.0)
    if x > 0:
        return one if lower else zero
    return zero if lower else one


def _do_del(x: float, xd: float, temp: float, lower: bool, log_p: bool) -> float:
    """do_del(xd) followed by swap_tail (the tail of pnorm_both at x)."""
    xsq = math.ldexp(math.trunc(math.ldexp(xd, 4)), -4)
    delta = (xd - xsq) * (xd + xsq)
    if log_p:
        cum = (-xsq * math.ldexp(xsq, -1)) - math.ldexp(delta, -1) + math.log(temp)
        # ccum is only computed when it is the tail returned (after the swap).
        if (lower and x > 0.0) or (not lower and x <= 0.0):
            ccum = math.log1p(
                -math.exp(-xsq * math.ldexp(xsq, -1)) * math.exp(-math.ldexp(delta, -1)) * temp
            )
        else:
            ccum = math.nan
    else:
        cum = math.exp(-xsq * math.ldexp(xsq, -1)) * math.exp(-math.ldexp(delta, -1)) * temp
        ccum = 1.0 - cum
    if x > 0.0:
        cum, ccum = ccum, cum
    return cum if lower else ccum


def pnorm(x: float, lower_tail: bool = True, log_p: bool = False) -> float:
    """R pnorm(x, lower.tail, log.p) (Cody's algorithm, pnorm.c)."""
    if math.isnan(x):
        return math.nan
    if math.isinf(x):
        if log_p:
            return 0.0 if (x > 0) == lower_tail else -math.inf
        return 1.0 if (x > 0) == lower_tail else 0.0
    return _pnorm_both(x, lower_tail, log_p)


def dnorm(x: float, give_log: bool = False) -> float:
    """R dnorm(x) (dnorm.c)."""
    if math.isnan(x):
        return x
    if math.isinf(x):
        return -math.inf if give_log else 0.0
    x = abs(x)
    if x >= 2 * math.sqrt(_DBL_MAX):
        return -math.inf if give_log else 0.0
    if give_log:
        return -(_M_LN_SQRT_2PI + 0.5 * x * x)
    if x < 5:
        return _M_1_SQRT_2PI * math.exp(-0.5 * x * x)
    if x > math.sqrt(-2 * _M_LN2 * (-1021 + 1 - 53)):
        return 0.0
    x1 = math.ldexp(round(math.ldexp(x, 16)), -16)
    x2 = x - x1
    return _M_1_SQRT_2PI * (math.exp(-0.5 * x1 * x1) * math.exp((-0.5 * x2 - x1) * x2))


