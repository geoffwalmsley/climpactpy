def _stirl_series(n: float, nn: float, k: int) -> float:
    """(S0-(S1-(...(S[k-1] - S[k]/nn)/nn ...)/nn)/n as written out in stirlerr."""
    acc = _S[k - 1] - _S[k] / nn
    for j in range(k - 2, -1, -1):
        acc = _S[j] - acc / nn
    return acc / n


def stirlerr(n: float) -> float:
    """R stirlerr(n): log(n!) - log(sqrt(2 pi n) (n / e)^n) (stirlerr.c)."""
    if n <= 23.5:
        nn = n + n
        if n <= 15.0 and nn == int(nn):
            return _SFERR_HALVES[int(nn)]
        if n <= 5.25:
            if n >= 1.0:
                l_n = math.log(n)
                return libm_lgamma(n) + n * (1 - l_n) + math.ldexp(l_n - _M_LN_2PI, -1)
            return lgamma1p(n) - (n + 0.5) * math.log(n) + n - _M_LN_SQRT_2PI
        nn = n * n
        if n > 12.8:
            return _stirl_series(n, nn, 6)
        if n > 12.3:
            return _stirl_series(n, nn, 7)
        if n > 8.9:
            return _stirl_series(n, nn, 8)
        if n > 7.3:
            return _stirl_series(n, nn, 10)
        if n > 6.6:
            return _stirl_series(n, nn, 12)
        if n > 6.1:
            return _stirl_series(n, nn, 14)
        return _stirl_series(n, nn, 16)
    nn = n * n
    if n > 15.7e6:
        return _S[0] / n
    if n > 6180:
        return (_S[0] - _S[1] / nn) / n
    if n > 205:
        return _stirl_series(n, nn, 2)
    if n > 86:
        return _stirl_series(n, nn, 3)
    if n > 27:
        return _stirl_series(n, nn, 4)
    return _stirl_series(n, nn, 5)


